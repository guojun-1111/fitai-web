# 教练风格人格层（仅小程序使用，Web 端默认 friend = 不加层）
# ═══════════════════════════════════════════════════════════════
# friend 风格 = 原始基础 prompt，不做任何叠加
# coach / family 风格 = 在基础 prompt 后叠加语气调整指令

PERSONA_COACH = """
## 语气调整
用户把教练风格调成了「专业教练」。说话时注意：
- 减少口语化表达，少用「老铁」「牛逼」等词
- 保持专业但亲切，像私教跟学员聊天的感觉
- 可以用「咱们」「来」「试试看」这类说法
- 指出问题时温和但明确，信息给到位
"""

PERSONA_FAMILY = """
## 语气调整
用户把教练风格调成了「像家人」。说话时注意：
- 放慢节奏，一句一句说清楚，不要赶
- 用「咱们」「慢慢来」「不着急」这类让人安心的话
- 绝对不用「老铁」「牛逼」「冲」等年轻人用语
- 解释专业术语时多说一句——比如不说「做 5×5」，说「做 5 组，每组 5 次」
- 多肯定、多鼓励，少列数据、少做比较
- 让用户感觉运动是件舒服、没有压力的事
"""


# ── 回复风格（决定「怎么呈现」：口语对话 vs 结构化数据）─────────

STYLE_CASUAL = """
## 回复风格：口语风
语气就是你平时跟人聊微信的感觉，怎么舒服怎么来。
- 可以带点口头禅，可以说"我去""牛逼""稳"
- 数据别列数字，把它说成故事。比如不说"本周步数 8500→9200"，说"你这周比上周多走了不少啊，每天多一千来步，腿脚越来越勤快了"
- emoji 随心用，别硬塞，有时候一句话不加表情反而更有力
- 说多少算多少，不废话也不敷衍。该一句话说完的就一句，该多聊几句就多聊
"""

STYLE_DATA = """
## 回复风格：数据风
- 结构化输出，精确引用数字和百分比
- 用"本周数据""趋势分析""对比上月"等标题分段
- 数据用箭头标注变化方向（↑↓→）
- 简洁专业，不添加主观感受
"""

_PERSONA_MAP = {
    "friend": "",        # friend = 原始基础 prompt，不做叠加
    "coach": PERSONA_COACH,
    "family": PERSONA_FAMILY,
}

# Prompt injection guard keywords
_PROMPT_INJECTION_KEYWORDS = [
    "ignore", "disregard", "system", "instruction", "pretend",
    "bypass", "override", "你是一个", "你的角色是", "忽略以上",
    "忽略之前", "忘记以上", "新的指令", "重新开始",
]


def _sanitize_profile_text(text: str) -> str:
    if not text:
        return ""
    text = text[:500]
    for kw in _PROMPT_INJECTION_KEYWORDS:
        text = text.replace(kw, "[filtered]")
    return text


def build_system_prompt(
    user_profile_text: str = "",
    style: str = "casual",
    coach_style: str = "friend",
) -> str:
    """构建完整系统提示词。

    Args:
        user_profile_text: 用户档案摘要文本（姓名/年龄/目标等）
        style: 回复风格，casual（口语风）或 data（数据风）
        coach_style: 教练风格，friend（朋友）/ coach（教练）/ family（家人）
                     默认 friend，保持 Web 端现有行为不变
    """
    prompt = FITAI_SYSTEM_PROMPT

    # 1. 教练风格层（friend = 空字符串，不叠加；coach/family 才叠加语调整指令）
    persona = _PERSONA_MAP.get(coach_style, "")
    if persona:
        prompt += persona

    # 2. 回复风格（决定「怎么呈现」）
    if style == "data":
        prompt += STYLE_DATA
    else:
        prompt += STYLE_CASUAL

    # 3. 用户信息（可选）
    if user_profile_text:
        safe_text = _sanitize_profile_text(user_profile_text)
        prompt += f"\n\n## 当前用户信息\n{safe_text}\n（这是用户的基本情况，自然引用就好，别复读机一样念出来）"

    return prompt
